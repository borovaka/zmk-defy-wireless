"""Package the nRF52820 firmware for the RP2040 to install through rf_bootloader.

The image takes the stock radio application's slot at 0x1C000, behind the
untouched MBR, S113 and rf_bootloader. Its seal is the 28-byte record the
bootloader validates and stores at 0x3D000, the same layout Dygma's keyscanner
sends for the stock application. The version in the seal is derived from the
image, so every change to the firmware is a new version, and it never equals
the stock application's: Dygma's keyscanner reinstalls its own application
when it finds a different one, which is how Bazecor takes the radio back to
stock. The C source embeds both in the halves' ZMK firmware.
"""

import argparse
from pathlib import Path
import struct
import sys
import zlib

from package_factory import pack_seal, read_ihex, SEAL, seal_crc_ok


PROGRAM_START = 0x1C000
SLOT_END = 0x39000
# The nRF52820's 32 KiB of RAM.
RAM_START = 0x20000000
RAM_END = 0x20008000
# rf_bootloader programs one word past every write, so the slot's last word stays free.
MAX_LENGTH = SLOT_END - PROGRAM_START - 4
STOCK_VERSION = 0x00010201
# A seal never carries these: no seal at all reads as 0xFFFFFFFF.
RESERVED_VERSIONS = (0, STOCK_VERSION, 0xFFFFFFFF)


def validate_program(program):
    if not 8 <= len(program) <= MAX_LENGTH or len(program) % 4:
        raise ValueError(f"radio program must be word aligned and at most {MAX_LENGTH} bytes")
    stack, reset = struct.unpack_from("<2I", program)
    if stack % 8 or not RAM_START < stack <= RAM_END:
        raise ValueError("initial stack pointer is outside aligned nRF52820 SRAM")
    if not reset & 1 or not PROGRAM_START + 8 <= (reset & ~1) < PROGRAM_START + len(program):
        raise ValueError("reset vector is outside the radio application image or is not Thumb")


def image_version(program):
    version = zlib.crc32(program)
    return version ^ 0x80000000 if version in RESERVED_VERSIONS else version


def make_package(memory):
    if not memory or min(memory) != PROGRAM_START or max(memory) >= PROGRAM_START + MAX_LENGTH:
        raise ValueError(f"radio application must be linked at 0x{PROGRAM_START:x} "
                         f"and end before 0x{PROGRAM_START + MAX_LENGTH:x}")
    if any(address not in memory for address in range(PROGRAM_START, PROGRAM_START + 8)):
        raise ValueError("incomplete radio vector table")
    length = (max(memory) + 1 - PROGRAM_START + 3) & ~3
    program = bytearray(b"\xff" * length)
    for address, value in memory.items():
        program[address - PROGRAM_START] = value
    validate_program(program)
    reset = struct.unpack_from("<I", program, 4)[0] & ~1
    if reset not in memory or reset + 1 not in memory:
        raise ValueError("reset vector points into missing radio application data")
    program = bytes(program)
    seal = make_seal(program)
    verify_package(program, seal)
    return program, seal


def make_seal(program):
    validate_program(program)
    return pack_seal(PROGRAM_START, len(program), zlib.crc32(program), image_version(program))


def verify_package(program, seal):
    if len(seal) != SEAL.size:
        raise ValueError("radio seal must be exactly 28 bytes")
    kind, size, _, start, length, program_crc, version = SEAL.unpack(seal)
    if kind != 1 or size != SEAL.size or start != PROGRAM_START:
        raise ValueError("unsupported radio seal layout")
    if not seal_crc_ok(seal):
        raise ValueError("radio seal CRC mismatch")
    if length != len(program):
        raise ValueError("radio program length does not match its seal")
    if zlib.crc32(program) != program_crc:
        raise ValueError("radio program CRC mismatch")
    validate_program(program)
    if version != image_version(program):
        raise ValueError("radio seal version does not match the image")
    return {"program_start": start, "program_length": length, "version": version}


def c_array(name, data):
    rows = ",\n    ".join(", ".join(f"0x{byte:02x}" for byte in data[offset:offset + 16])
                          for offset in range(0, len(data), 16))
    return f"const uint8_t {name}[{len(data)}] __attribute__((aligned(4))) = {{\n    {rows}\n}};\n"


def c_source(program, seal):
    info = verify_package(program, seal)
    return ("/* Generated by scripts/package_radio.py. */\n\n"
            "#include <dygma/defy_radio_image.h>\n\n" +
            c_array("defy_radio_image", program) +
            f"const size_t defy_radio_image_size = {len(program)};\n" +
            c_array("defy_radio_image_seal", seal) +
            f"const uint32_t defy_radio_image_version = 0x{info['version']:08x}u;\n")


def main():
    parser = argparse.ArgumentParser(description="Package the radio firmware for the halves to install.")
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output-bin", type=Path, required=True)
    parser.add_argument("--output-seal", type=Path, required=True)
    parser.add_argument("--output-source", type=Path, required=True)
    args = parser.parse_args()
    paths = (args.input, args.output_bin, args.output_seal, args.output_source)
    if len({path.resolve() for path in paths}) != len(paths):
        parser.error("input and output paths must be distinct")
    try:
        memory = read_ihex(args.input.read_text(), minimum=PROGRAM_START, maximum=SLOT_END)
        program, seal = make_package(memory)
        source = c_source(program, seal)
        args.output_bin.write_bytes(program)
        args.output_seal.write_bytes(seal)
        args.output_source.write_text(source)
    except (OSError, UnicodeError, ValueError) as error:
        sys.exit(f"{args.input}: {error}")
    print(f"Packaged {len(program)} radio bytes at 0x{PROGRAM_START:x}, "
          f"version 0x{image_version(program):08x}, {MAX_LENGTH - len(program)} bytes to spare.")


if __name__ == "__main__":
    main()
